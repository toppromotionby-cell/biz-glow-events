/** Полная системная инструкция для модели. */
export function systemPrompt(ctx: {
  isAdmin: boolean;
  roles: string[];
  webSearch: boolean;
  planOnly: boolean;
  now?: Date;
}): string {
  const now = ctx.now ?? new Date();
  const stamp = now.toLocaleString("ru-RU", { timeZone: "Europe/Minsk" });
  return [
    ROLE,
    `Сейчас ${stamp} (Минск). Сайт: ${SITE}.`,
    `Права собеседника: роли ${ctx.roles.length ? ctx.roles.join(", ") : "нет"}; ${
      ctx.isAdmin ? "это администратор — доступны внутренние данные" : "это не администратор — внутренние данные не выдаём"
    }.`,
    ctx.webSearch ? "Интернет-поиск разрешён." : "Интернет-поиск ОТКЛЮЧЁН администратором — работай только по данным портала.",
    ctx.planOnly ? "Включён строгий режим: любое действие, меняющее данные, только через план на утверждение." : "",
    SOURCE_ORDER,
    FORMAT_RULES,
    BOUNDARY_RULES,
    PLAN_RULES,
    SCREENSHOT_RULES,
    KNOWLEDGE_RULES,
    HYGIENE_RULES,
    FALLBACK_RULES,
  ]
    .filter(Boolean)
    .join("\n\n");
}

/** Справка по командам с учётом роли. */
export function helpText(kind: "guest" | "staff" | "admin"): string {
  if (kind === "guest") {
    return [
      `👋 Это <b>${ASSISTANT_NAME}</b> — рабочий бот админ-панели event-hub.by.`,
      "",
      "Чат не привязан к сотруднику. Откройте админку → «Помощник» → «Привязать Telegram»,",
      "получите код и отправьте его сюда одним сообщением.",
    ].join("\n");
  }
  const lines = [
    `<b>${ASSISTANT_NAME}</b> — что я умею:`,
    "",
    "<b>Файлы и документы</b>",
    "/files — что есть за период (КП, документы, презентации, кадровые)",
    "/doc <i>запрос</i> — найти документ и получить PDF в чат",
    "",
    "<b>Знания и поиск</b>",
    "/kb <i>запрос</i> — поиск по базе знаний · /kb add <i>факт</i> — записать",
    "/ask <i>вопрос</i> — ответ по данным портала",
    "/find <i>запрос</i> — поиск в интернете со ссылками",
    "/sources — источники последнего ответа",
    "",
    "<b>Работа</b>",
    "/stats <i>день|неделя|месяц</i> — сводка",
    "/hygiene — состояние данных и запуск проверки",
    "/plan <i>задача</i> — собрать план на утверждение",
    "",
    "<b>Прочее</b>",
    "/mute, /unmute — уведомления · /reset — сбросить контекст",
    "",
    "Можно писать обычным текстом или голосом — я разберусь.",
  ];
  if (kind === "admin") {
    lines.push("", "Вам как администратору доступны внутренние документы с себестоимостью и маржой.");
  }
  return lines.join("\n");
}

/** Короткий отказ вне зоны ответственности. */
export function refusal(reason: string): string {
  return `🚫 ${reason}\n\nЯ работаю с документами, заявками, каталогом, базой знаний и гигиеной данных портала. Наберите /help — покажу список.`;
}
