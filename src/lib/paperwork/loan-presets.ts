function loan(opts: {
  id: string;
  name: string;
  description: string;
  preamble: string;
  lenderText: string;
  borrowerText: string;
  signerTitle: string;
  signerName: string;
}): PwPreset {
  return {
    id: opts.id,
    name: opts.name,
    description: opts.description,
    category: "contracts",
    doc_type: "loan",
    blocks: [
      h("ДОГОВОР ДЕНЕЖНОГО ЗАЙМА № {{Номер документа}}"),
      p("г. Минск\t\t\t\t«{{Дата договора}}»", false),
      p(opts.preamble),
      ...body(),
      normalizeBlock({
        type: "parties",
        leftTitle: "Займодавец",
        leftText: opts.lenderText,
        rightTitle: "Заемщик",
        rightText: opts.borrowerText,
      }),
      normalizeBlock({ type: "spacer", size: 16 }),
      normalizeBlock({
        type: "signature",
        signerTitle: opts.signerTitle,
        signerName: opts.signerName,
        withStamp: true,
      }),
    ],
  };
}

