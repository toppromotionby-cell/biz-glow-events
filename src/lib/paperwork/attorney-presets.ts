// Шаблоны доверенностей ООО «Топ промоушн» по образцам компании.
// Постоянная часть (доверитель, директор, перечень полномочий) зашита в текст,
// заполняются только данные поверенного, номер, дата и срок действия.
import { normalizeBlock, type PwBlock } from "@/lib/paperwork/model";
import type { PwPreset } from "@/lib/paperwork/preset-types";

const h = (text: string, align: "left" | "center" = "center") =>
  normalizeBlock({ type: "heading", text, align });
const p = (text: string, indent = true) =>
  normalizeBlock({ type: "paragraph", text, align: "justify", indent });
const list = (items: string[], ordered: boolean) => normalizeBlock({ type: "list", items, ordered });
const gap = (size = 16) => normalizeBlock({ type: "spacer", size });
const sign = () =>
  normalizeBlock({
    type: "signature",
    signerTitle: "Директор",
    signerName: "Кузнецов Дмитрий Владимирович",
    withStamp: true,
  });

const PLACE_DATE = "г. {{Город}}                                                {{Дата}}";

/** Преамбула: кого и на каком основании уполномочивает общество. */
function grantor(role: string): string {
  return `Настоящей доверенностью Общество с ограниченной ответственностью «Топ промоушн» (далее – Общество), в лице директора Кузнецова Дмитрия Владимировича, действующего на основании Устава, уполномочивает ${role}{{ФИО поверенного}}, зарегистрированную(ого) по адресу: {{Адрес регистрации поверенного}}; {{Документ поверенного}}; идентификационный номер {{Идентификационный номер}}`;
}

function goodsDocsBlocks(): PwBlock[] {
  return [
    h("ДОВЕРЕННОСТЬ № {{Номер документа}}"),
    p(PLACE_DATE, false),
    p(`${grantor("")} совершать следующие действия от имени ООО «ТОП ПРОМОУШН»:`),
    list(
      [
        "забирать и передавать документы общества в государственные органы, в том числе в районные администрации и Минский городской исполнительный комитет;",
        "забирать и передавать документы и ТМЦ общества в РУП «БЕЛПОЧТА»;",
        "забирать и отправлять ТМЦ, документы, в том числе посылки, письма общества в курьерских службах «Автолайт», «СДЭК» и т. д.;",
        "забирать и передавать документы и ТМЦ общества в других организациях;",
        "передавать документы от имени общества для участия в тендерных закупках.",
      ],
      false,
    ),
    p("Доверенность выдана без права передоверия на срок по {{Срок действия}}.", false),
    gap(18),
    sign(),
  ];
}

