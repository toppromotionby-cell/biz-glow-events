/** Подтверждение усвоенного правила. */
export const LEARNED_ACK = "🧠 Запомнил. Второй бот тоже в курсе.";

/** Подтверждение забытого правила. */
export function forgottenAck(count: number): string {
  return count > 0 ? `🧽 Забыл (${count}). Второй бот тоже забыл.` : "Такого в памяти не нашёл.";
}

/**
 * Вычищает «нарисованные» кнопки из текста модели: строки вида
 * «Кнопки: ✅ Утвердить / ✏️ Правки / 🚫 Отменить» или отдельные строки-подписи.
 */
export function stripFakeButtons(text: string): string {
  const labels = BUTTON_LABELS.join("|");
  const line = new RegExp(
    `^\\s*(?:[•\\-–—*]\\s*)?(?:<b>)?(?:кнопк[\\p{L}]*\\s*[:—-]\\s*)?[^\\p{L}\\n]{0,3}\\s*(?:${labels})[^\\p{L}\\n]*$`,
    "iu",
  );
  const kept = text
    .split("\n")
    .filter((raw) => {
      const l = raw.trim();
      if (!l) return true;
      if (!new RegExp(`(${labels})`, "i").test(l)) return true;
      // Оставляем содержательные предложения, режем только «панели кнопок».
      const hits = BUTTON_LABELS.filter((b) => new RegExp(b, "i").test(l)).length;
      if (hits >= 2) return false;
      return !line.test(l);
    })
    .join("\n");
  return kept.replace(/\n{3,}/g, "\n\n").trim();
}

/** Единый блок правил для системного промпта любого бота. */
export function commonRules(): string {
  return [FORMAT_RULES, PLAN_RULES, SCREENSHOT_RULES, SHARED_LEARNING_RULES].join("\n\n");
}
